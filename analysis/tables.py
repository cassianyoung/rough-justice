def slash_breaks(s):
    """A served model string, quoted as served, as a cell that may break after a slash but never at a hyphen (P
    columns forbid hyphen breaks)."""
    parts = s.split("/")
    return cell(parts[0], *(x for p in parts[1:] for x in (("raw", "/\\allowbreak{}"), p)))


