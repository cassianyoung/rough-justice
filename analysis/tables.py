# the worked dismissal pair the introduction uses (one run 259 dismissal pair all the way down)
DESIGN_PAIR = "D2"


def table_design(frames, pid=DESIGN_PAIR):
    """Table 2: the five conditions, each with what the model sees and the example as the models read it. Every example
    is cut from the prompts themselves, and each cut is asserted to reassemble the prompt it came from."""
    u = frames["units"]
    p = next(x for x in frames["pairs"] if x["id"] == pid)
    side = u[f"A|{pid}"]["prompts"]["side_FO"]["user"]
    alone = u[f"B|{pid}"]["prompts"]["F"]["user"]
    case, q = alone.split(" Judged by", 1)
    q = "Judged by" + q
    principle = u[f"C|{pid}"]["prompts"]["F"]["user"][:-len(alone)].strip()
    rule = u[f"D|{pid}"]["prompts"]["F"]["user"][:-len(alone)].strip()
    e_line = u[f"E|{pid}"]["prompts"]["line"]["user"]
    assert u[f"C|{pid}"]["prompts"]["F"]["user"] == f"{principle} {alone}"
    assert u[f"D|{pid}"]["prompts"]["F"]["user"] == f"{rule} {alone}"
    assert principle == frames["domains"][p["domain"]]["standard"] and rule == p["line"]
    assert e_line == f"{rule} {case} {p['E'][0]} {q}"
    lead, body = side.split("Case ", 1)
    labels = [x.split(":", 1)[0] for x in side.split("Case ")[1:]]
    c1, rest = body.split(f" Case {labels[1]}: ", 1)
    c1 = c1.split(": ", 1)[1]
    c2, side_q = rest.split(" Judged by", 1)
    s1, shared = c1.split(". ", 1)
    s2, shared2 = c2.split(". ", 1)
    assert shared == shared2 and case.endswith(shared.replace("The employer", p["name"])), pid
    ex_side = f"Case {labels[0]}: {s1}. [...] Case {labels[1]}: {s2}. [...]"
    rows = [["Side by side", "Both cases in one prompt", ex_side],
            ["Alone", "One case", case],
            ["Alone, told in principle", "One case, plus a sentence on who is held to more", principle],
            ["Alone, told a precise rule", "One case, plus a rule that decides it", rule],
            ["Outside the rule", "The precise-rule case, plus a failing the rule does not cover", p["E"][0]]]
    E = lambda t: [("raw", "\\emph{"), t, ("raw", "}")]
    cap = cell("Five of the seven conditions (the worked example and the failing outside it are described in the "
               "text), with one dismissal pair (", ("pairid", pid), ") quoted as the models read it. [...] "
               "stands for the conduct both cases share, given in full in the Alone row (side by side, the firm is ",
               *E("the employer"), "). The told-in-principle sentence and the precise rule come before the case, and the "
               "failing outside the rule after it. Side by side ends ", *E("Judged by" + side_q), "; every other prompt "
               "ends ", *E(q), " Each alone condition is read for both firms separately; the failing outside the rule is "
               "read for the firm held to less.")
    return Table("table2_design", cap,
                 "tab:design", ["Condition", "What the model sees", "Example"], rows,
                 "P{0.17\\textwidth}P{0.24\\textwidth}P{0.51\\textwidth}", wide=True, data=True)


