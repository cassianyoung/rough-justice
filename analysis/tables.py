# ── a table spec, rendered to LaTeX and to a preview ───────────────────────────────────
class Table:
    def __init__(self, name, caption, label, header, rows, colspec, wide=False, data=False, size="small",
                 longtable=False, groups=None, note=None, colsep=None):
        self.__dict__.update(locals())
        del self.__dict__["self"]

    def tex(self):
        head = DATA_HEAD if self.data else GEN_HEAD
        hdr = " & ".join("".join(seg_tex(s) for s in (h if isinstance(h, list) else [h])) for h in self.header)
        body = []
        for r in self.rows:
            if r == "midrule":
                body.append("\\midrule")
            elif isinstance(r, tuple) and r[0] == "group":
                txt = r[1] if "\\model{" in r[1] else tex_escape(r[1])
                body.append(f"\\multicolumn{{{len(self.header)}}}{{l}}{{\\textit{{{txt}}}}} \\\\")
            else:
                body.append(" & ".join("".join(seg_tex(s) for s in (c if isinstance(c, list) else [c])) for c in r)
                            + " \\\\")
        cap = "".join(seg_tex(s) for s in (self.caption if isinstance(self.caption, list) else [self.caption]))
        if self.longtable:
            return (head + f"{{\\{self.size}\n\\begin{{longtable}}{{{self.colspec}}}\n"
                    f"\\caption{{{cap}}}\\label{{{self.label}}}\\\\\n\\toprule\n{hdr} \\\\\n\\midrule\n\\endfirsthead\n"
                    f"\\toprule\n{hdr} \\\\\n\\midrule\n\\endhead\n\\bottomrule\n\\endfoot\n"
                    + "\n".join(body) + "\n\\end{longtable}\n}\n")
        env = "table*" if self.wide else "table"
        note = ""
        if self.note:                                           # notes under the rule, above the caption
            note = "\n".join("\\par\\smallskip{\\footnotesize\\raggedright " + "".join(seg_tex(x) for x in n) + "\\par}"
                             for n in self.note) + "\n"
        sep = f"\\setlength{{\\tabcolsep}}{{{self.colsep}}}\n" if self.colsep else ""
        return (head + f"\\begin{{{env}}}[t]\n\\centering\n\\{self.size}\n" + sep +
                f"\\begin{{tabular}}{{{self.colspec}}}\n\\toprule\n{hdr} \\\\\n\\midrule\n" + "\n".join(body) +
                f"\n\\bottomrule\n\\end{{tabular}}\n" + note +
                f"\\caption{{{cap}}}\n\\label{{{self.label}}}\n\\end{{{env}}}\n")

    def text_rows(self, nums):
        f = lambda c: "".join(seg_text(s, nums) for s in (c if isinstance(c, list) else [c]))
        rows = []
        for r in self.rows:
            if r == "midrule":
                rows.append(None)
            elif isinstance(r, tuple) and r[0] == "group":
                rows.append([r[1]] + [""] * (len(self.header) - 1))
            else:
                rows.append([f(c) for c in r])
        return [f(h) for h in self.header], rows, f(self.caption)


