# ── cells: a cell is a list of segments, each a literal string or ("m", macro) ───────────
def tex_escape(s):
    rep = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_", "{": r"\{",
           "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}", "£": r"\pounds{}", "–": "--",
           "’": "'", "‘": "`", "“": "``", "”": "''"}
    return "".join(rep.get(c, c) for c in s)


def seg_tex(seg):
    if isinstance(seg, tuple):
        if seg[0] == "m":
            return "\\" + seg[1] + "{}"
        if seg[0] == "model":
            return "\\model{" + tex_escape(seg[1]) + "}"
        if seg[0] == "pairid":
            return "\\pairid{" + seg[1] + "}"
        if seg[0] == "raw":
            return seg[1]
        if seg[0] == "prov":                                    # provisional (run 262), highlighted; refused in a final build
            return "\\Prov{" + seg[1] + "}"
    return tex_escape(seg)


def seg_text(seg, nums):
    if isinstance(seg, tuple):
        if seg[0] == "m":
            if seg[1] not in nums:
                raise KeyError(f"no macro {seg[1]}")
            return nums[seg[1]]["printed"].replace("\\%", "%").replace("{,}", ",").replace("\\$", "$")
        if seg[0] == "raw":
            return re.sub(r"\\[a-zA-Z]+|[{}]", "", seg[1].replace("\\%", "%"))
        if seg[0] == "prov":
            if "Prov" + seg[1] not in nums:
                raise KeyError(f"no provisional macro Prov{seg[1]}")
            return nums["Prov" + seg[1]]["printed"].replace("\\%", "%") + " (prov)"
        return seg[1]
    return seg


def cell(*segs):
    return list(segs)


def share_ci(name):
    return cell(M(name), " [", M(name + "Lo"), ", ", M(name + "Hi"), "]")


def share_ci_stacked(name):
    """The share, with its interval beneath in tiny type: for grids too wide to carry intervals inline."""
    return cell(("raw", "\\begin{tabular}[t]{@{}c@{}}"), M(name), ("raw", "\\\\{\\tiny["), M(name + "Lo"), ", ",
                M(name + "Hi"), ("raw", "]}\\end{tabular}"))


