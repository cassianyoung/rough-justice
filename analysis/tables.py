def build(frames, reads, res, nums):
    ts = [table1(frames), table_design(frames), tableD_wrong_verdicts(nums), tableA1(reads), tableB1(), tableB2(), tableB3(nums), tableC(frames),
          tableD_consensus(res), tableD_knows(nums), tableE_readout(nums), tableB4_haiku(nums)]
    for k, mname, lab, _ in O.MEASURES:
        if k in ("A", "B", "C", "D", "E"):
            ts.append(tableD(nums, k, mname, lab))
    ts.append(tableD_example(nums))
    return ts


def check_macros(ts, nums):
    missing = set()
    for t in ts:
        for r in t.rows + [t.header, t.caption if isinstance(t.caption, list) else []] + list(t.note or []):
            if r == "midrule" or (isinstance(r, tuple)):
                continue
            for c in r:
                for s in (c if isinstance(c, list) else [c]):
                    if isinstance(s, tuple) and s[0] == "m" and s[1] not in nums:
                        missing.add(s[1])
    return missing


def preview(t, nums, path):
    import textwrap
    import matplotlib
    matplotlib.use("pdf")
    import matplotlib.pyplot as plt
    from matplotlib.backends.backend_pdf import PdfPages
    plt.rcParams.update({"pdf.fonttype": 42, "font.family": "serif", "font.serif": ["Times New Roman", "Times"],
                         "font.size": 7})
    header, rows, cap = t.text_rows(nums)
    width = 6.3 if t.wide or t.longtable else 3.15
    ncol = len(header)
    total = int(width * 17)                                  # characters per line at 7 pt, roughly
    longest = [max(max((len(w) for w in header[i].split()), default=4),
                   *(max((len(w) for w in r[i].split()), default=1) for r in rows if r)) for i in range(ncol)]
    want = [max(len(header[i]), *(len(r[i]) for r in rows if r)) for i in range(ncol)]
    chars = [max(min(w, 34), l) + 2 for w, l in zip(want, longest)]
    while sum(chars) > total and max(chars) > 12:
        i = chars.index(max(chars))
        chars[i] -= 1
    if sum(chars) < total:
        i = want.index(max(want))
        chars[i] += total - sum(chars)
    weights = chars
    tot = sum(weights)
    wrap = lambda s, i: textwrap.fill(s, chars[i] - 2, break_long_words=False) if s else ""
    lines = [[wrap(h, i) for i, h in enumerate(header)]] + [None if r is None else [wrap(c, i) for i, c in enumerate(r)]
                                                             for r in rows]
    heights = [1 + max(c.count("\n") for c in r) if r else 0.3 for r in lines]
    per_page, pages, cur, h = 58, [], [], 0
    for r, hh in zip(lines[1:], heights[1:]):
        if h + hh > per_page and cur:
            pages.append(cur); cur, h = [], 0
        cur.append((r, hh)); h += hh
    pages.append(cur)
    with PdfPages(path, metadata={"Creator": "analysis/tables.py", "CreationDate": None}) as pdf:
        for pi, page in enumerate(pages):
            total = heights[0] + sum(hh for _, hh in page) + 4 + cap.count("\n")
            lh = 0.115
            fig = plt.figure(figsize=(width, max(1.0, total * lh + 0.3)))
            y = 1.0 - 0.08 / fig.get_figheight()
            xs = [0.03 + 0.95 * sum(weights[:i]) / tot for i in range(ncol)]
            capw = textwrap.fill(f"{t.label}: {cap}" + (" (continued)" if pi else ""), int(width * 17))
            fig.text(0.03, y, capw, va="top", ha="left", fontsize=7, style="italic")
            y -= (capw.count("\n") + 1.6) * lh / fig.get_figheight()
            for r, hh in [(lines[0], heights[0])] + page:
                if r is None:
                    fig.add_artist(plt.Line2D([0.03, 0.98], [y + 0.02 * lh, y + 0.02 * lh], lw=0.4, color="#888888"))
                    y -= 0.3 * lh / fig.get_figheight()
                    continue
                for x, c in zip(xs, r):
                    fig.text(x, y, c, va="top", ha="left", fontsize=7,
                             fontweight="bold" if r is lines[0] else "normal")
                y -= hh * lh / fig.get_figheight()
                if r is lines[0]:
                    fig.add_artist(plt.Line2D([0.03, 0.98], [y + 0.3 * lh / fig.get_figheight()] * 2, lw=0.6, color="k"))
            pdf.savefig(fig)
            plt.close(fig)


def write(ts, nums):
    os.makedirs(OUT, exist_ok=True)
    os.makedirs(PREVIEW, exist_ok=True)
    for t in ts:
        open(os.path.join(OUT, t.name + ".tex"), "w").write(t.tex())
        preview(t, nums, os.path.join(PREVIEW, t.name + ".pdf"))


