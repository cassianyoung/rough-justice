#!/usr/bin/env python3
"""macros.py : the only path by which a number reaches the paper.

The analysis builds a dict {name: (value, source)} and calls write_macros(); this writes paper/numbers.tex, which
paper/main.tex reads with \\input{numbers}, and paper/numbers.json, which records where each number came from. No
number is typed into the text: tools/check_typed_numbers.py refuses a .tex body that carries a digit.

    python analysis/macros.py --selftest
    python analysis/macros.py --empty        # (re)writes the empty generated file the skeleton reads
"""
import argparse, json, os, re, tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TEX = os.path.join(ROOT, "paper", "numbers.tex")
SIDECAR = os.path.join(ROOT, "paper", "numbers.json")
PREFIX = ""          # macros are named by what they measure (after run 259)
HEADER = ("% GENERATED by analysis/macros.py. Do not edit: every number in the paper is defined here and nowhere else.\n"
          "% Provenance of each macro: paper/numbers.json.\n")


def fmt(value, kind):
    if kind == "pct":          # a share in [0, 1], printed as a whole percentage
        return f"{round(100 * value):d}\\%"
    if kind == "pts":          # a difference of shares, printed in whole percentage points, signed
        return f"{round(100 * value):+d}"
    if kind == "ptsu":         # a size of change in whole percentage points, unsigned
        return f"{round(100 * abs(value)):d}"
    if kind == "int":
        return f"{int(value):,d}".replace(",", "{,}")
    if kind == "usd":
        return f"\\${value:.2f}"
    if kind.startswith("f"):   # f2, f3: fixed decimals
        return f"{value:.{int(kind[1:])}f}"
    if kind == "str":
        return str(value)
    if kind == "word":         # a small count, printed as a word
        return ("zero one two three four five six seven eight nine ten eleven twelve thirteen fourteen fifteen "
                "sixteen seventeen eighteen nineteen twenty").split()[int(value)]
    raise ValueError(f"unknown format {kind!r}")


def write_macros(values, tex=TEX, sidecar=SIDECAR, extra=None):
    """values: {name: {"value": v, "kind": k, "source": "file#key"}}. Names are letters only (LaTeX's rule).
    extra: optional {key: object} written into the sidecar under keys starting with '_' (never a macro name), for
    example the old-to-new mapping when macros are renamed."""
    lines, meta = [HEADER], {}
    for name in sorted(values):
        if not re.fullmatch(r"[A-Za-z]+", name):
            raise ValueError(f"macro name must be letters only: {name!r}")
        v = values[name]
        if not v.get("source"):
            raise ValueError(f"{name}: every number needs a source")
        text = fmt(v["value"], v["kind"])
        lines.append(f"\\newcommand{{\\{PREFIX}{name}}}{{{text}}}\n")
        meta[PREFIX + name] = {"printed": text, "value": v["value"], "kind": v["kind"], "source": v["source"],
                               **({"note": v["note"]} if v.get("note") else {})}
    for k, x in (extra or {}).items():
        if not k.startswith("_"):
            raise ValueError(f"sidecar extra keys start with '_': {k!r}")
        meta[k] = x
    open(tex, "w").write("".join(lines))
    open(sidecar, "w").write(json.dumps(meta, indent=1, sort_keys=True) + "\n")
    return len(meta)


def selftest():
    d = tempfile.mkdtemp()
    t, s = os.path.join(d, "n.tex"), os.path.join(d, "n.json")
    n = write_macros({"HOneSideShare": {"value": 0.8125, "kind": "pct", "source": "results/x.json#h1.side"},
                      "HOneDiff": {"value": 0.47, "kind": "pts", "source": "results/x.json#h1.diff"},
                      "NCalls": {"value": 12345, "kind": "int", "source": "results/x.json#calls"}}, t, s)
    body = open(t).read()
    assert n == 3 and "\\newcommand{\\HOneSideShare}{81\\%}" in body and "{\\HOneDiff}{+47}" in body
    assert "{\\NCalls}{12{,}345}" in body and json.load(open(s))["NCalls"]["source"] == "results/x.json#calls"
    for bad in ({"H1": {"value": 1, "kind": "int", "source": "x"}}, {"Ok": {"value": 1, "kind": "int", "source": ""}}):
        try:
            write_macros(bad, t, s)
            raise AssertionError("accepted a bad macro")
        except ValueError:
            pass
    print("selftest 3/3")


if __name__ == "__main__":
    a = argparse.ArgumentParser()
    a.add_argument("--selftest", action="store_true")
    a.add_argument("--empty", action="store_true")
    o = a.parse_args()
    if o.selftest:
        selftest()
    if o.empty:
        print(f"wrote {write_macros({})} macros to paper/numbers.tex")
